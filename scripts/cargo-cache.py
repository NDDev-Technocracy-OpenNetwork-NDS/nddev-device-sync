#!/usr/bin/env python3
"""Configure the shared NDS Cargo lane, or run with its complete pinned tools."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
MARKER = "# Generated by nddev-device-sync/scripts/cargo-cache.py\n"


def output(arguments, *, cwd=ROOT):
    return subprocess.check_output(arguments, cwd=cwd, text=True, timeout=30).strip()


def context():
    catalog = json.loads((ROOT / "contracts/module-catalog.json").read_text())
    allowed = {item["repository"] for item in catalog["modules"]} | {catalog["product"]}
    scope = ROOT.parent
    # Cargo's parent configuration must never cover unrelated projects.
    for child in scope.iterdir():
        if not child.is_dir() or child.name == ".cargo":
            continue
        if child.name not in allowed or not (child / ".git").exists():
            raise ValueError("the common parent must contain only registered NDS checkouts")
        remote = output(["git", "remote", "get-url", "origin"], cwd=child)
        expected = f"github.com/{catalog['organization']}/{child.name}"
        normalized = remote.removesuffix(".git").removeprefix("https://").replace("git@github.com:", "github.com/")
        if normalized.lower() != expected.lower():
            raise ValueError("an NDS checkout has a different provider identity")
    channel = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())["toolchain"]["channel"]
    binary = Path(output(["rustup", "which", "--toolchain", channel, "rustc"]))
    compiler = dict(line.split(": ", 1) for line in output([str(binary), "-vV"]).splitlines() if ": " in line)
    if compiler["release"] != channel:
        raise ValueError("the actual compiler differs from the pinned toolchain")
    lane = f"{channel}-{compiler['host']}-{compiler['commit-hash'][:12]}"
    return scope, binary.parent, lane


def cache_base():
    if os.name == "nt":
        root = Path(os.environ.get("LOCALAPPDATA", Path.home() / "AppData/Local"))
    elif sys.platform == "darwin":
        root = Path.home() / "Library/Caches"
    else:
        root = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache"))
    return root / "nds/cargo"


def configuration(scope, binary, lane, base=None):
    target = (base or cache_base()).expanduser().resolve() / lane
    text = MARKER + "[build]\n"
    for key, value in [("target-dir", target), ("build-dir", target / "build"), ("rustc", binary / "rustc"), ("rustdoc", binary / "rustdoc")]:
        text += f"{key} = {json.dumps(str(value), ensure_ascii=False)}\n"
    return scope / ".cargo/config.toml", target, text


def setup(base=None):
    scope, binary, lane = context()
    config, target, text = configuration(scope, binary, lane, base)
    if config.with_name("config").exists():
        raise ValueError("refuse to shadow an existing legacy Cargo configuration")
    original = config.read_bytes() if config.exists() else None
    if original is not None:
        if not original.decode().startswith(MARKER):
            raise ValueError("refuse to replace unrelated Cargo configuration")
        data = tomllib.loads(original.decode())
        if set(data) != {"build"} or not isinstance(data["build"], dict) or not set(data["build"]) <= {"target-dir", "build-dir", "rustc", "rustdoc"}:
            raise ValueError("refuse to replace locally extended Cargo configuration")
    config.parent.mkdir(exist_ok=True)
    target.mkdir(mode=0o700, parents=True, exist_ok=True)
    if not config.exists() or config.read_text() != text:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=config.parent,
                                         prefix="config.nds-", delete=False) as stream:
            pending = Path(stream.name)
            try:
                stream.write(text)
                stream.flush()
                os.fsync(stream.fileno())
            except BaseException:
                pending.unlink(missing_ok=True)
                raise
        try:
            if (config.read_bytes() if config.exists() else None) != original:
                raise ValueError("Cargo configuration changed during setup")
            pending.replace(config)
        finally:
            pending.unlink(missing_ok=True)
    return {"target_directory": str(target), "toolchain": lane, "configuration": str(config)}


def configured():
    scope, binary, lane = context()
    config = scope / ".cargo/config.toml"
    if not config.is_file() or not config.read_text().startswith(MARKER):
        raise ValueError("run cargo-cache.py setup first")
    data = tomllib.loads(config.read_text())["build"]
    target = Path(data["target-dir"])
    if (target.name != lane or not target.is_absolute() or data.get("build-dir") != str(target / "build")
            or data["rustc"] != str(binary / "rustc") or data["rustdoc"] != str(binary / "rustdoc")):
        raise ValueError("shared cache configuration differs from the pinned compiler; rerun setup")
    return binary, target


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="mode", required=True)
    commands.add_parser("setup").add_argument("--cache-root", type=Path)
    commands.add_parser("check")
    commands.add_parser("run").add_argument("command", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    if args.mode == "setup":
        print(json.dumps(setup(args.cache_root)))
    else:
        binary, target = configured()
        if args.mode == "check":
            print(json.dumps({"target_directory": str(target), "rustc": str(binary / "rustc")}))
            return 0
        command = args.command[1:] if args.command[:1] == ["--"] else args.command
        if not command:
            parser.error("run requires a command after --")
        environment = dict(os.environ, PATH=str(binary) + os.pathsep + os.environ.get("PATH", ""),
                           RUSTC=str(binary / "rustc"), RUSTDOC=str(binary / "rustdoc"))
        environment.setdefault("CARGO_TARGET_DIR", str(target))
        environment.setdefault("CARGO_BUILD_BUILD_DIR", str(Path(environment["CARGO_TARGET_DIR"]) / "build"))
        return subprocess.run(command, env=environment).returncode
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, OSError, subprocess.SubprocessError, KeyError) as error:
        raise SystemExit(f"NDS Cargo cache: {error}") from None
